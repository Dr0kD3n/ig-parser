export function resolveNichePresets(value) {
  if (!Array.isArray(value) || value.length === 0) return NICHE_PRESETS;
  return value.every((item) => item?.catalogVersion === NICHE_PRESETS_VERSION)
    ? value
    : NICHE_PRESETS;
}


const normalizeCategoryText = (value) =>
  String(value || '')
    .trim()
    .toLocaleLowerCase('ru')
    .replace(/[^a-zа-яё0-9]+/gi, ' ')
    .replace(/\s+/g, ' ')
    .trim();

export function extractDonorNiche({ niche, keyword, city } = {}) {
  const nicheValue = String(niche || '').trim();
  if (nicheValue) return nicheValue;

  const keywordValue = String(keyword || '').trim();
  if (!keywordValue) return '';

  const normalizedKeyword = normalizeCategoryText(keywordValue);
  const cityAliases = String(city || '')
    .split('|')
    .map((value) => value.trim())
    .filter(Boolean)
    .sort((a, b) => b.length - a.length);

  for (const cityAlias of cityAliases) {
    const normalizedCity = normalizeCategoryText(cityAlias);
    if (normalizedKeyword === normalizedCity) return '';
    if (normalizedKeyword.startsWith(`${normalizedCity} `)) {
      return keywordValue.slice(cityAlias.length).trim();
    }
  }

  return keywordValue;
}

export function resolveNicheCategory(value, presets = NICHE_PRESETS) {
  const source = String(value || '').trim();
  if (!source) return '';

  const aliases = source
    .split('|')
    .map((alias) => ({ label: alias.trim(), normalized: normalizeCategoryText(alias) }))
    .filter((alias) => alias.normalized);
  let bestMatch = null;

  for (const section of resolveNichePresets(presets)) {
    for (const item of section.items || []) {
      for (const keyword of item.keywords || []) {
        const normalizedKeyword = normalizeCategoryText(keyword);
        if (normalizedKeyword.length < 4) continue;
        for (const alias of aliases) {
          let score = 0;
          if (alias.normalized === normalizedKeyword) score = 1000 + normalizedKeyword.length;
          else if (alias.normalized.includes(normalizedKeyword)) score = 500 + normalizedKeyword.length;
          else if (normalizedKeyword.includes(alias.normalized) && alias.normalized.length >= 4) {
            score = 250 + alias.normalized.length;
          }
          if (score > (bestMatch?.score || 0)) bestMatch = { section, item, score };
        }
      }
    }
  }

  if (bestMatch) return `${bestMatch.section.name} - ${bestMatch.item.name}`;

  const sectionMatch = resolveNichePresets(presets).find((section) => {
    const sectionName = normalizeCategoryText(section.name);
    return aliases.some(
      (alias) => alias.normalized.startsWith(sectionName) || sectionName.startsWith(alias.normalized)
    );
  });
  return sectionMatch ? `${sectionMatch.name} - ${aliases[0].label}` : aliases[0].label;
}
